    s32 item1;
    s32 item2;
    u32 size1;
    u32 size2;

    if (charID < 0 || charID >= 54) {
        return NULL;
    }
    if (itemSlot < 0 || itemSlot >= 6) {
        return NULL;
    }
    kind = lbl_800F743C[charID];
    item1 = charID * SUBITEMS_PER_CHAR + lbl_800F7424[kind][itemSlot][0];
    item2 = charID * SUBITEMS_PER_CHAR + lbl_800F7424[kind][itemSlot][1];
